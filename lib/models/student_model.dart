class StudentProfile {
  final String name;
  final String studentId;
  final String department;
  final String levelTerm;
  final String email;
  final String phone;

  const StudentProfile({
    required this.name,
    required this.studentId,
    required this.department,
    required this.levelTerm,
    required this.email,
    required this.phone,
  });
}
